-- GTX-A 수서~동탄 노선·역·평일 시간표 시드 (#20, 방향·중간역 추가 #26).
--
-- 출처: GTX-A 공식 사이트의 열차시간표 API (www.gtx-a.com/trainTimeTable.do), 2026-09-20 수집.
-- 좌표는 위키백과. 역 코드(X108~X111)와 노선 코드(L09)는 공식 사이트가 쓰는 값 그대로다.
-- 좌표 교차검증: 위도가 공식 역 순서(수서 → 성남 → 구성 → 동탄)를 따라 단조 감소한다.
--
-- 평일만 넣는 이유: dayTypeCode=1(평일)과 3(휴일) 응답이 9개 역 전부 완전히 동일하게 온다.
-- 출퇴근 시간대가 조밀한 평일 패턴이 그대로라 휴일 시간표가 같은 게 아니라 API가 파라미터를
-- 무시하는 것으로 보여, 틀린 시각을 넣느니 비워 둔다.
--
-- 방향(direction_code): 원본 시간표가 시각별로 UP_TIME_N/DN_TIME_N을 따로 준다. stationIF.do의
-- prevStNo/nextStNo 체인이 X108 수서 → X109 성남 → X110 구성 → X111 동탄이고, 종착역이 각각
-- 한쪽 방향만 갖는 것으로 극성이 확정된다 — **UP = 역번호가 작아지는 쪽(수서 방면),
-- DN = 커지는 쪽(동탄 방면)**. transit_line_stops와 같은 어휘를 그대로 쓴다.
-- 종착역(수서 DN만, 동탄 UP만)은 원본에도 한 방향뿐이라 여기서도 한 방향만 들어간다.
--
-- R__ 반복 마이그레이션이라 체크섬이 바뀔 때마다 다시 적용된다. 여러 번 돌려도 결과가 같게
-- 노선·역·정류장 순서는 upsert, 시간표는 (노선, 정류장, day_type, 방향) 단위로 지우고 다시 넣는다.

