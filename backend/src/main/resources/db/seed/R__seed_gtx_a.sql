-- 방향별 정류장 순서. 이 테이블은 TAGO 동기화로만 채워져서 GTX는 비어 있었고, 비어 있으면
-- LegDirectionResolver.resolve()가 GTX 구간에 대해 null을 돌려준다 (#26).
-- seq_no는 진행 방향 순서다: DN은 수서→동탄, UP은 동탄→수서.
INSERT INTO transit_line_stops (transit_line_id, stop_id, direction_code, seq_no)
SELECT l.id, s.id, t.direction_code, t.seq_no
FROM transit_lines l
CROSS JOIN (VALUES
    ('X108', 'DN', 1),
    ('X109', 'DN', 2),
    ('X110', 'DN', 3),
    ('X111', 'DN', 4),
    ('X111', 'UP', 1),
    ('X110', 'UP', 2),
    ('X109', 'UP', 3),
    ('X108', 'UP', 4)
) AS t(stn, direction_code, seq_no)
JOIN transit_stops s
  ON s.mode = 'GTX' AND s.stdg_cd = 'GTX-A' AND s.external_id = t.stn
WHERE l.mode = 'GTX' AND l.stdg_cd = 'GTX-A' AND l.external_id = 'L09'
ON CONFLICT (transit_line_id, direction_code, seq_no)
DO UPDATE SET stop_id = EXCLUDED.stop_id;

-- 시간표는 (노선, 정류장, day_type, 방향) 단위로 교체한다. 방향을 키에서 빼면 한 방향을
-- 다시 넣을 때 반대 방향이 같이 지워진다.
DELETE FROM transit_schedules ts
USING transit_lines l, transit_stops s, (VALUES
    ('X108', 'DN'),
    ('X109', 'UP'),
    ('X109', 'DN'),
    ('X110', 'UP'),
    ('X110', 'DN'),
    ('X111', 'UP')
) AS d(stn, direction_code)
WHERE ts.transit_line_id = l.id
  AND ts.stop_id = s.id
  AND ts.day_type = 'WEEKDAY'
  AND ts.direction_code = d.direction_code
  AND l.mode = 'GTX' AND l.stdg_cd = 'GTX-A' AND l.external_id = 'L09'
  AND s.mode = 'GTX' AND s.stdg_cd = 'GTX-A' AND s.external_id = d.stn;

